func TestFixedGroups(t *testing.T) {
	cases := map[string]Group{
		"internal/ui/model_test.go":      Tests,
		"web/src/list.test.tsx":          Tests,
		"internal/transcript/testdata/a": Tests,
		"go.sum":                         Generated,
		"api/v1/user.pb.go":              Generated,
	}
	for p, want := range cases {
		g, ok := Fixed(p, nil, false)
		assert.True(t, ok, p)
		assert.Equal(t, want, g, p)
	}
	g, ok := Fixed("internal/x/x.go", []byte("// Code generated by sqlc. DO NOT EDIT.\npackage x\n"), false)
	assert.True(t, ok)
	assert.Equal(t, Generated, g)
	_, ok = Fixed("internal/x/x.go", []byte("package x\n"), false)
	assert.False(t, ok)
}

func TestArrange(t *testing.T) {
	files := []File{{Path: "a.go"}, {Path: "a2.go"}, {Path: "b.go"}, {Path: "m.go"}, {Path: "z.go"}, {Path: "a_test.go", Group: Tests}}
	notes := []Note{{Path: "z.go", Group: "changes", Note: "core"}, {Path: "m.go", Group: "changes"}, {Path: "a.go", Group: "imports"}, {Path: "b.go", Group: "refactor"}, {Path: "a_test.go", Group: "changes"}}
	got := Arrange(files, notes)
	var paths []string
	for _, f := range got {
		paths = append(paths, f.Path)
	}
	assert.Equal(t, []string{"z.go", "m.go", "a2.go", "b.go", "a.go", "a_test.go"}, paths)
	assert.Equal(t, "core", got[0].Note)
	assert.Equal(t, Tests, got[5].Group)
}

func TestMergeOrder(t *testing.T) {
	pr := func(n int, base, head string) PR {
		return PR{Number: n, URL: head, Repo: "o/r", Base: base, Head: head}
	}
	got := MergeOrder([]PR{pr(3, "b", "c"), pr(9, "main", "x"), pr(5, "main", "b"), pr(4, "c", "d")})
	var nums []int
	for _, p := range got {
		nums = append(nums, p.Number)
	}
	assert.Equal(t, []int{5, 3, 4, 9}, nums)
}
