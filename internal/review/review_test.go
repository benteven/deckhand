package review

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestFixedGroups(t *testing.T) {
	cases := map[string]Group{
		"internal/ui/model_test.go":      Tests,
		"web/src/list.test.tsx":          Tests,
		"internal/transcript/testdata/a": Tests,
		"go.sum":                         Generated,
		"api/v1/user.pb.go":              Generated,
	}
	for p, want := range cases {
		g, ok := Fixed(p, nil, false)
		assert.True(t, ok, p)
		assert.Equal(t, want, g, p)
	}
	g, ok := Fixed("internal/x/x.go", []byte("// Code generated by sqlc. DO NOT EDIT.\npackage x\n"), false)
	assert.True(t, ok)
	assert.Equal(t, Generated, g)
	_, ok = Fixed("internal/x/x.go", []byte("package x\n"), false)
	assert.False(t, ok)
}

func TestArrange(t *testing.T) {
	files := []File{{Path: "a.go"}, {Path: "b.go"}, {Path: "c.go"}, {Path: "d.go"}, {Path: "a_test.go", Group: Tests}}
	notes := []Note{{Path: "c.go", Group: "changes", Note: "core"}, {Path: "a.go", Group: "imports"}, {Path: "b.go", Group: "refactor"}, {Path: "a_test.go", Group: "changes"}}
	got := Arrange(files, notes)
	var paths []string
	for _, f := range got {
		paths = append(paths, f.Path)
	}
	assert.Equal(t, []string{"c.go", "d.go", "b.go", "a.go", "a_test.go"}, paths)
	assert.Equal(t, "core", got[0].Note)
	assert.Equal(t, Tests, got[4].Group)
}
